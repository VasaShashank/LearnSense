"""
Teacher Collective Knowledge State and Teaching Optimizer Models (§10).
"""

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class InterventionStatus(str, Enum):
    PROPOSED = "PROPOSED"
    APPROVED = "APPROVED"
    DELIVERED = "DELIVERED"
    EVALUATED = "EVALUATED"


class ConceptMasteryDistribution(BaseModel):
    """Aggregate mastery distribution across a cohort of learners for one concept."""
    concept_id: str
    canonical_name: str
    sample_size: int
    mean_mastery: float
    median_mastery: float
    p25_mastery: float
    p75_mastery: float
    proportion_mastered: float  # P(L) >= 0.70
    proportion_struggling: float  # P(L) < 0.40
    average_attempts: float
    struggling_learner_ids: List[str] = Field(default_factory=list)


class PrerequisiteGapCluster(BaseModel):
    """Prerequisite bottleneck affecting multiple learners in the cohort."""
    target_concept_id: str
    target_concept_name: str
    prerequisite_concept_id: str
    prerequisite_concept_name: str
    affected_learner_count: int
    severity: float  # 0.0 - 1.0


class MisconceptionCluster(BaseModel):
    """A recurring misconception observed across multiple learners."""
    misconception_id: str
    concept_id: str
    description: str
    affected_learner_count: int
    prevalence: float  # fraction of cohort


class ClassKnowledgeState(BaseModel):
    """
    Class-level aggregated learning state across all enrolled learners.
    Ensures privacy preservation while providing actionable instructional intelligence.
    """
    class_id: str
    subject_id: str
    subject_title: str = ""
    total_enrolled: int
    active_learners: int
    concept_distributions: Dict[str, ConceptMasteryDistribution] = Field(default_factory=dict)
    prerequisite_gap_clusters: List[PrerequisiteGapCluster] = Field(default_factory=list)
    misconception_clusters: List[MisconceptionCluster] = Field(default_factory=list)
    overall_class_readiness: float = 0.0


class StudentInterventionGroup(BaseModel):
    """A cluster of students needing a specific instructional approach."""
    group_name: str
    instructional_focus: str
    learner_ids: List[str]
    suggested_resource: Optional[str] = None


class TeachingActionRecommendation(BaseModel):
    """Actionable recommendation produced by the Teaching Optimizer."""
    priority: int
    action_type: str  # REVISE_PREREQUISITE, DIRECT_INSTRUCTION, WORKED_EXAMPLE, REASSESSMENT
    target_concept_id: str
    target_concept_name: str
    rationale: str
    allocated_time_minutes: int
    student_groups: List[StudentInterventionGroup] = Field(default_factory=list)
    recommended_probe_concept_ids: List[str] = Field(default_factory=list)


class TeachingInterventionPlan(BaseModel):
    """Complete lesson / intervention plan generated by Teaching Optimizer for teacher approval."""
    intervention_id: str
    class_id: str
    subject_id: str
    created_at_iso: str
    status: InterventionStatus = InterventionStatus.PROPOSED
    target_learning_objective: str
    total_class_duration_minutes: int = 50
    actions: List[TeachingActionRecommendation] = Field(default_factory=list)
    teacher_notes: Optional[str] = None
    approved_at_iso: Optional[str] = None


class InterventionOutcome(BaseModel):
    """Outcome measurement closing the teacher intervention feedback loop (§10.3)."""
    intervention_id: str
    class_id: str
    concept_id: str
    pre_intervention_mean_mastery: float
    post_intervention_mean_mastery: float
    mastery_gain: float
    pre_struggling_count: int
    post_struggling_count: int
    remediation_effective: bool
    summary: str
