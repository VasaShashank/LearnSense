def bkt_step_features(
    targets: pd.DataFrame,
    config: BKTConfig,
    *,
    policy: str = "primary_only",
) -> pd.DataFrame:
    if targets.empty:
        raise ValueError("Cannot construct BKT features from an empty target table.")
    if targets["interaction_id"].duplicated().any():
        raise ValueError("Target table must have unique interaction_id values.")

    sorted_targets = targets.sort_values(
        by=["student_id", "sequence_index", "timestamp_utc"],
        kind="mergesort",
    ).reset_index(drop=True)
    replay = replay_interactions(sorted_targets, config=config, policy=policy)

    step_frame = pd.DataFrame(
        [
            {
                "interaction_id": step.interaction_id,
                "bkt_p_prior": float(step.p_prior),
                "bkt_p_pred": float(step.p_pred),
                "bkt_p_posterior": float(step.p_posterior),
                "bkt_p_next": float(step.p_next),
            }
            for step in replay.steps
        ]
    )

    merged = targets.merge(step_frame, on="interaction_id", how="left", validate="one_to_one")
    feature_columns = ["bkt_p_prior", "bkt_p_pred", "bkt_p_posterior", "bkt_p_next"]
    if merged[feature_columns].isna().any().any():
        raise ValueError("BKT replay did not produce a prediction for every target row.")

    merged["bkt_logit_prior"] = _logit(merged["bkt_p_prior"])
    merged["bkt_logit_pred"] = _logit(merged["bkt_p_pred"])
    merged["bkt_logit_posterior"] = _logit(merged["bkt_p_posterior"])
    merged["bkt_logit_next"] = _logit(merged["bkt_p_next"])
    return merged


@dataclass(frozen=True)
class EffectTable:
    population_probability: float
    population_logit: float
    probabilities: Dict[str, float]
    logits: Dict[str, float]
    counts: Dict[str, int]
    key_name: str

    def map_logit(self, values: Iterable[Any]) -> np.ndarray:
        mapped = pd.Series(values, dtype="object").astype(str).map(self.logits)
        return mapped.fillna(self.population_logit).to_numpy(dtype=float)

    def map_count(self, values: Iterable[Any]) -> np.ndarray:
        mapped = pd.Series(values, dtype="object").astype(str).map(self.counts)
        return mapped.fillna(0).to_numpy(dtype=float)


def fit_effect_table(
    train_df: pd.DataFrame,
    key_column: str,
    *,
    prior_strength_m: float = DEFAULT_ITEM_SHRINKAGE_M,
) -> EffectTable:
    if key_column not in train_df.columns:
        raise ValueError(f"Training DataFrame missing key column '{key_column}'.")
    if len(train_df) == 0:
        raise ValueError("Cannot fit an effect table on empty training data.")

    y = train_df["correct"].to_numpy(dtype=int)
    population_probability = float(
        np.clip(float(y.mean()), PROBABILITY_EPSILON, 1.0 - PROBABILITY_EPSILON)
    )
    grouped = (
        pd.DataFrame(
            {
                "key": train_df[key_column].astype(str),
                "correct": y,
            }
        )
        .groupby("key")["correct"]
        .agg(["sum", "count"])
    )

    m = float(prior_strength_m)
    probabilities: Dict[str, float] = {}
    logits: Dict[str, float] = {}
    counts: Dict[str, int] = {}
    for key, row in grouped.iterrows():
        k = int(row["sum"])
        n = int(row["count"])
        probability = float(
            np.clip(
                (k + m * population_probability) / (n + m),
                PROBABILITY_EPSILON,
                1.0 - PROBABILITY_EPSILON,
            )
        )
        probabilities[str(key)] = probability
        logits[str(key)] = float(_logit([probability])[0])
        counts[str(key)] = n

    return EffectTable(
        population_probability=population_probability,
        population_logit=float(_logit([population_probability])[0]),
        probabilities=probabilities,
        logits=logits,
        counts=counts,
        key_name=key_column,
    )


class CombinedItemBKTModel:
    """Logistic combination of item difficulty and a pre-response BKT state.

    The item term is a train-only smoothed empirical logit. The BKT term is the
    logit of either the pre-response predicted response probability or the prior
    mastery belief, selected explicitly by the caller. Unseen items fall back to
    the training population logit.
    """

    def __init__(
        self,
        *,
        bkt_feature: Optional[str] = "p_pred",
        include_bkt: bool = True,
        include_concept: bool = False,
        C: float = 1.0,
        prior_strength_m: float = DEFAULT_ITEM_SHRINKAGE_M,
        random_state: int = DEFAULT_SEED,
    ) -> None:
        if include_bkt and bkt_feature not in {"p_pred", "p_prior", "p_next"}:
            raise ValueError(f"Unsupported bkt_feature '{bkt_feature}'.")
        if C <= 0:
            raise ValueError(f"Regularization strength C must be positive. Found {C}.")

        self.bkt_feature = bkt_feature if include_bkt else None
        self.include_bkt = bool(include_bkt)
        self.include_concept = bool(include_concept)
        self.C = float(C)
        self.prior_strength_m = float(prior_strength_m)
        self.random_state = int(random_state)
        self.item_effects_: Optional[EffectTable] = None
        self.concept_effects_: Optional[EffectTable] = None
        self.model_: Optional[LogisticRegression] = None
        self.is_fitted = False

    def _bkt_column(self) -> str:
        if not self.include_bkt or self.bkt_feature is None:
            raise RuntimeError("This model does not include a BKT feature.")
        return {
            "p_pred": "bkt_logit_pred",
            "p_prior": "bkt_logit_prior",
            "p_next": "bkt_logit_next",
        }[self.bkt_feature]

    def _design_matrix(self, df: pd.DataFrame) -> np.ndarray:
        if self.item_effects_ is None:
            raise RuntimeError("CombinedItemBKTModel must be fitted before prediction.")

        columns = [self.item_effects_.map_logit(df["question_id"])]
        if self.include_concept:
            if self.concept_effects_ is None:
                raise RuntimeError("Concept effect table is not fitted.")
            columns.append(self.concept_effects_.map_logit(df["primary_concept_id"]))
        if self.include_bkt:
            bkt_column = self._bkt_column()
            if bkt_column not in df.columns:
                raise ValueError(f"Target DataFrame missing BKT feature '{bkt_column}'.")
            columns.append(df[bkt_column].to_numpy(dtype=float))

        matrix = np.column_stack(columns).astype(float)
        if not np.isfinite(matrix).all():
            raise ValueError("Combined model design matrix contains non-finite values.")
        return matrix

    def fit(self, train_targets: pd.DataFrame) -> "CombinedItemBKTModel":
        if "correct" not in train_targets.columns:
            raise ValueError("Training targets must contain the 'correct' column.")
        self.item_effects_ = fit_effect_table(
            train_targets,
            "question_id",
            prior_strength_m=self.prior_strength_m,
        )
        if self.include_concept:
            self.concept_effects_ = fit_effect_table(
                train_targets,
                "primary_concept_id",
                prior_strength_m=self.prior_strength_m,
            )

        X = self._design_matrix(train_targets)
        y = train_targets["correct"].to_numpy(dtype=int)
        self.model_ = LogisticRegression(
            C=self.C,
            solver="lbfgs",
            max_iter=2000,
            random_state=self.random_state,
        )
        self.model_.fit(X, y)
        self.is_fitted = True
        return self

    def predict_proba(self, targets: pd.DataFrame) -> np.ndarray:
        if not self.is_fitted or self.model_ is None:
            raise RuntimeError("CombinedItemBKTModel must be fitted before prediction.")
        X = self._design_matrix(targets)
        return _clip_probabilities(self.model_.predict_proba(X)[:, 1])

    def feature_names(self) -> List[str]:
        names = ["item_logit"]
        if self.include_concept:
            names.append("concept_logit")
        if self.include_bkt:
            names.append(f"bkt_logit_{self.bkt_feature}")
        return names

    def coefficients(self) -> Dict[str, float]:
        if not self.is_fitted or self.model_ is None:
            raise RuntimeError("CombinedItemBKTModel must be fitted before coefficients.")
        return {
            name: float(value)
            for name, value in zip(self.feature_names(), self.model_.coef_[0])
        }


