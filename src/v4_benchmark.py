def _eligible_mask(df: pd.DataFrame) -> pd.Series:
    mask = df["correct"].notna() & df["correct"].isin([0, 1])
    mask &= df["interaction_id"].notna()
    mask &= df["student_id"].notna()
    mask &= df["question_id"].notna()
    mask &= df["primary_concept_id"].notna()
    mask &= df["concept_ids"].notna()
    mask &= df["sequence_index"].notna() & (df["sequence_index"] >= 1)
    return mask


def canonical_targets(
    interactions: pd.DataFrame,
    split: str,
    *,
    train_item_counts: Optional[pd.Series] = None,
) -> pd.DataFrame:
    missing = [c for c in REQUIRED_TARGET_COLUMNS if c not in interactions.columns]
    if missing:
        raise ValueError(f"Interactions DataFrame missing required target columns: {missing}")

    if split not in {"train", "validation", "test"}:
        raise ValueError(f"Unsupported split '{split}'. Expected train, validation, or test.")

    split_df = interactions.loc[interactions["student_split"].eq(split)].copy()
    if split_df.empty:
        raise ValueError(f"Split '{split}' contains no interactions.")

    eligible = _eligible_mask(split_df)
    targets = split_df.loc[eligible].copy()
    targets = targets.sort_values(
        by=["student_id", "sequence_index", "timestamp_utc"],
        kind="mergesort",
    ).reset_index(drop=True)

    if targets["interaction_id"].duplicated().any():
        raise ValueError(f"Duplicate interaction_id values found in split '{split}'.")

    targets["prior_interactions"] = targets["sequence_index"].astype(int) - 1
    targets["concept_count"] = (
        targets["concept_ids"]
        .fillna(targets["primary_concept_id"])
        .astype(str)
        .map(lambda value: len([c for c in value.split(";") if c.strip()]))
        .astype(int)
    )
    targets["is_multi_concept"] = targets["concept_count"] > 1

    if train_item_counts is not None:
        counts = targets["question_id"].astype(str).map(train_item_counts).fillna(0).astype(int)
        targets["item_train_count"] = counts
        targets["item_seen_in_train"] = targets["item_train_count"] > 0
    else:
        targets["item_train_count"] = -1
        targets["item_seen_in_train"] = pd.NA

    return targets


def eligibility_audit(interactions: pd.DataFrame) -> Dict[str, Any]:
    missing = [c for c in REQUIRED_TARGET_COLUMNS if c not in interactions.columns]
    if missing:
        raise ValueError(f"Interactions DataFrame missing required target columns: {missing}")

    result: Dict[str, Any] = {
        "rows_total": int(len(interactions)),
        "duplicate_interaction_ids": int(interactions["interaction_id"].duplicated().sum()),
        "missing_values": {
            column: int(interactions[column].isna().sum())
            for column in REQUIRED_TARGET_COLUMNS
        },
        "splits": {},
    }

    for split in ("train", "validation", "test"):
        split_df = interactions.loc[interactions["student_split"].eq(split)]
        eligible = _eligible_mask(split_df)
        sequence_unique = True
        chronology_valid = True
        if not split_df.empty:
            sequence_unique = bool(
                not split_df.duplicated(subset=["student_id", "sequence_index"]).any()
            )
            ordered = split_df.sort_values(
                by=["student_id", "sequence_index", "timestamp_utc"],
                kind="mergesort",
            )
            chronology_valid = bool(
                ordered.groupby("student_id")["timestamp_utc"].apply(
                    lambda values: values.is_monotonic_increasing
                ).all()
            )
        result["splits"][split] = {
            "learners": int(split_df["student_id"].nunique()),
            "interactions": int(len(split_df)),
            "eligible_interactions": int(eligible.sum()),
            "ineligible_interactions": int((~eligible).sum()),
            "observed_positive_rate": float(split_df.loc[eligible, "correct"].mean())
            if eligible.any()
            else None,
            "assessment_rate": float(split_df["is_assessment"].mean())
            if "is_assessment" in split_df.columns and len(split_df)
            else None,
            "sequence_index_unique_per_learner": sequence_unique,
            "chronology_valid": chronology_valid,
        }

    return result


def item_exposure_audit(interactions: pd.DataFrame) -> Dict[str, Any]:
    item_sets = {
        split: set(
            interactions.loc[interactions["student_split"].eq(split), "question_id"].astype(str)
        )
        for split in ("train", "validation", "test")
    }
    concept_sets = {
        split: set(
            interactions.loc[
                interactions["student_split"].eq(split), "primary_concept_id"
            ].astype(str)
        )
        for split in ("train", "validation", "test")
    }

    train_counts = (
        interactions.loc[interactions["student_split"].eq("train")]
        .groupby("question_id")
        .size()
        .sort_values()
    )
    test_counts = (
        interactions.loc[interactions["student_split"].eq("test")]
        .groupby("question_id")
        .size()
    )

    return {
        "items_per_split": {split: len(values) for split, values in item_sets.items()},
        "concepts_per_split": {split: len(values) for split, values in concept_sets.items()},
        "test_items_seen_in_train": len(item_sets["test"] & item_sets["train"]),
        "test_items_unseen_in_train": len(item_sets["test"] - item_sets["train"]),
        "validation_items_seen_in_train": len(item_sets["validation"] & item_sets["train"]),
        "validation_items_unseen_in_train": len(item_sets["validation"] - item_sets["train"]),
        "test_item_coverage_in_train": float(
            len(item_sets["test"] & item_sets["train"]) / max(len(item_sets["test"]), 1)
        ),
        "train_item_attempt_quantiles": {
            "min": int(train_counts.min()),
            "p05": float(train_counts.quantile(0.05)),
            "p25": float(train_counts.quantile(0.25)),
            "median": float(train_counts.quantile(0.50)),
            "p75": float(train_counts.quantile(0.75)),
            "p95": float(train_counts.quantile(0.95)),
            "max": int(train_counts.max()),
        },
        "test_item_attempt_quantiles": {
            "min": int(test_counts.min()),
            "p05": float(test_counts.quantile(0.05)),
            "p25": float(test_counts.quantile(0.25)),
            "median": float(test_counts.quantile(0.50)),
            "p75": float(test_counts.quantile(0.75)),
            "p95": float(test_counts.quantile(0.95)),
            "max": int(test_counts.max()),
        },
    }


