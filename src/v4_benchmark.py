def _logit(values: Sequence[float]) -> np.ndarray:
    p = np.clip(np.asarray(values, dtype=float), PROBABILITY_EPSILON, 1.0 - PROBABILITY_EPSILON)
    return np.log(p / (1.0 - p))


def _clip_probabilities(values: Sequence[float]) -> np.ndarray:
    return np.clip(np.asarray(values, dtype=float), PROBABILITY_EPSILON, 1.0 - PROBABILITY_EPSILON)


def _constant_auc(y: np.ndarray, p: np.ndarray) -> float:
    if len(np.unique(y)) < 2:
        return float("nan")
    if np.allclose(p, p[0]):
        return 0.5
    return float(roc_auc_score(y, p))


