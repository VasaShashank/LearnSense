def static_baseline_predictions(
    models: Mapping[str, Any],
    targets: pd.DataFrame,
) -> Dict[str, np.ndarray]:
    return {
        name: _clip_probabilities(model.predict_proba(targets))
        for name, model in models.items()
    }


def select_combined_model(
    train_targets: pd.DataFrame,
    validation_targets: pd.DataFrame,
    *,
    bkt_feature: Optional[str] = "p_pred",
    include_bkt: bool = True,
    include_concept: bool = False,
    c_grid: Sequence[float] = DEFAULT_C_GRID,
    prior_strength_m: float = DEFAULT_ITEM_SHRINKAGE_M,
) -> Tuple[CombinedItemBKTModel, float, List[Dict[str, Any]]]:
    rows: List[Dict[str, Any]] = []
    best_key: Optional[Tuple[float, float]] = None
    best_model: Optional[CombinedItemBKTModel] = None
    best_c: Optional[float] = None

    for c_value in c_grid:
        model = CombinedItemBKTModel(
            bkt_feature=bkt_feature,
            include_bkt=include_bkt,
            include_concept=include_concept,
            C=float(c_value),
            prior_strength_m=prior_strength_m,
        ).fit(train_targets)
        probabilities = model.predict_proba(validation_targets)
        metrics = evaluate_predictions(validation_targets["correct"], probabilities)
        row = {
            "C": float(c_value),
            "log_loss": metrics["log_loss"],
            "brier_score": metrics["brier_score"],
            "roc_auc": metrics["roc_auc"],
            "expected_calibration_error": metrics["expected_calibration_error"],
        }
        rows.append(row)
        key = (float(metrics["log_loss"]), float(c_value))
        if best_key is None or key < best_key:
            best_key = key
            best_model = model
            best_c = float(c_value)

    if best_model is None or best_c is None:
        raise RuntimeError("Combined model selection failed to produce a candidate.")
    return best_model, best_c, rows


def evaluate_model_predictions(
    targets: pd.DataFrame,
    predictions: Mapping[str, Sequence[float]],
) -> Dict[str, Dict[str, Any]]:
    results: Dict[str, Dict[str, Any]] = {}
    for name, values in predictions.items():
        probabilities = _clip_probabilities(values)
        if len(probabilities) != len(targets):
            raise ValueError(
                f"Prediction length mismatch for '{name}': {len(probabilities)} vs {len(targets)}."
            )
        metrics = evaluate_predictions(targets["correct"], probabilities)
        metrics["student_count"] = int(targets["student_id"].nunique())
        metrics["mean_predicted_probability"] = float(probabilities.mean())
        results[name] = metrics
    return results


def _student_index_arrays(student_ids: np.ndarray) -> Tuple[np.ndarray, List[np.ndarray]]:
    unique_students = np.unique(student_ids)
    positions = {student: [] for student in unique_students}
    for index, student in enumerate(student_ids):
        positions[student].append(index)
    return unique_students, [np.asarray(positions[student], dtype=int) for student in unique_students]


def paired_cluster_bootstrap(
    targets: pd.DataFrame,
    predictions: Mapping[str, Sequence[float]],
    comparisons: Sequence[Tuple[str, str]],
    *,
    n_resamples: int = DEFAULT_BOOTSTRAP_RESAMPLES,
    seed: int = DEFAULT_SEED,
    auc_resamples: Optional[int] = None,
) -> Dict[str, Any]:
    """Student-clustered paired bootstrap for log loss, Brier, and AUROC deltas.

    Sign convention: delta = candidate - reference. For log loss and Brier,
    negative values favor the candidate. For AUROC, positive values favor the
    candidate. AUROC may use a smaller resample budget because it requires a
    rank computation for every model on every resample.
    """

    if n_resamples <= 0:
        raise ValueError("n_resamples must be positive.")
    auc_resamples = int(n_resamples if auc_resamples is None else auc_resamples)
    if auc_resamples <= 0:
        raise ValueError("auc_resamples must be positive.")
    auc_resamples = min(auc_resamples, int(n_resamples))
    full_auc = auc_resamples == int(n_resamples)
    y = targets["correct"].to_numpy(dtype=int)
    student_ids = targets["student_id"].astype(str).to_numpy()
    unique_students, student_indices = _student_index_arrays(student_ids)
    student_position = {student: index for index, student in enumerate(unique_students)}

    probabilities = {
        name: _clip_probabilities(values) for name, values in predictions.items()
    }
    for name, values in probabilities.items():
        if len(values) != len(y):
            raise ValueError(f"Prediction length mismatch for '{name}'.")

    losses = {
        name: -(y * np.log(values) + (1 - y) * np.log(1.0 - values))
        for name, values in probabilities.items()
    }
    brier = {
        name: (y - values) ** 2
        for name, values in probabilities.items()
    }

    required_models = sorted(
        {model for pair in comparisons for model in pair if model in probabilities}
    )
    auc_models = set(required_models)

    deltas: Dict[str, Dict[str, List[float]]] = {}
    for candidate, reference in comparisons:
        if candidate not in probabilities or reference not in probabilities:
            continue
        key = f"{candidate}_minus_{reference}"
        deltas[key] = {"log_loss": [], "brier": [], "auc": []}

    rng = np.random.default_rng(seed)
    for _ in range(n_resamples):
        sampled_students = rng.choice(unique_students, size=len(unique_students), replace=True)
        sampled_indices = np.concatenate(
            [student_indices[student_position[student]] for student in sampled_students]
        )
        y_boot = y[sampled_indices]
        if len(np.unique(y_boot)) < 2:
            continue

        boot_metrics: Dict[str, Dict[str, float]] = {}
        for name in required_models:
            boot_metrics[name] = {
                "log_loss": float(losses[name][sampled_indices].mean()),
                "brier": float(brier[name][sampled_indices].mean()),
            }
            if full_auc and name in auc_models:
                boot_metrics[name]["auc"] = _constant_auc(y_boot, probabilities[name][sampled_indices])

        for candidate, reference in comparisons:
            key = f"{candidate}_minus_{reference}"
            if key not in deltas:
                continue
            for metric in ("log_loss", "brier", "auc"):
                if metric == "auc" and not full_auc:
                    continue
                value = boot_metrics[candidate][metric] - boot_metrics[reference][metric]
                if np.isfinite(value):
                    deltas[key][metric].append(float(value))

    if not full_auc:
        auc_rng = np.random.default_rng(int(seed) + 1)
        for _ in range(auc_resamples):
            sampled_students = auc_rng.choice(
                unique_students, size=len(unique_students), replace=True
            )
            sampled_indices = np.concatenate(
                [student_indices[student_position[student]] for student in sampled_students]
            )
            y_boot = y[sampled_indices]
            if len(np.unique(y_boot)) < 2:
                continue
            boot_auc = {
                name: _constant_auc(y_boot, probabilities[name][sampled_indices])
                for name in required_models
            }
            for candidate, reference in comparisons:
                key = f"{candidate}_minus_{reference}"
                if key not in deltas:
                    continue
                value = boot_auc[candidate] - boot_auc[reference]
                if np.isfinite(value):
                    deltas[key]["auc"].append(float(value))

    summaries: Dict[str, Any] = {}
    for key, metric_values in deltas.items():
        metric_summary: Dict[str, Any] = {}
        for metric, values in metric_values.items():
            if not values:
                metric_summary[f"delta_{metric}"] = {
                    "mean": None,
                    "std": None,
                    "ci_lower_95": None,
                    "ci_upper_95": None,
                    "is_significant_95": None,
                    "valid_resamples": 0,
                }
                continue
            arr = np.asarray(values, dtype=float)
            lower, upper = np.percentile(arr, [2.5, 97.5])
            p_value = float(
                min(
                    1.0,
                    2.0 * min(float(np.mean(arr <= 0.0)), float(np.mean(arr >= 0.0))),
                )
            )
            metric_summary[f"delta_{metric}"] = {
                "mean": float(np.mean(arr)),
                "std": float(np.std(arr)),
                "ci_lower_95": float(lower),
                "ci_upper_95": float(upper),
                "p_value": p_value,
                "is_significant_95": bool(lower * upper > 0),
                "valid_resamples": int(len(arr)),
            }
        summaries[key] = metric_summary

    return {
        "seed": int(seed),
        "n_resamples": int(n_resamples),
        "auc_resamples": int(auc_resamples),
        "cluster_count": int(len(unique_students)),
        "comparisons": summaries,
        "sign_convention": {
            "log_loss": "candidate - reference; negative favors candidate",
            "brier": "candidate - reference; negative favors candidate",
            "auc": "candidate - reference; positive favors candidate",
        },
    }


