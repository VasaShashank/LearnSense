    validation_predictions["item_logit_logistic"] = item_logit_model.predict_proba(validation)
    validation_predictions["item_concept_logit_logistic"] = item_concept_logit_model.predict_proba(
        validation
    )

    test_predictions["bkt_concept_fitted"] = _clip_probabilities(test["bkt_p_pred"])
    test_predictions["combined_item_bkt"] = combined_model.predict_proba(test)
    test_predictions["combined_item_bkt_prior"] = combined_prior_model.predict_proba(test)
    test_predictions["combined_item_concept_bkt"] = combined_concept_model.predict_proba(test)
    test_predictions["item_logit_logistic"] = item_logit_model.predict_proba(test)
    test_predictions["item_concept_logit_logistic"] = item_concept_logit_model.predict_proba(test)

    validation_metrics = evaluate_model_predictions(validation, validation_predictions)
    test_metrics = evaluate_model_predictions(test, test_predictions)

    bootstrap = paired_cluster_bootstrap(
        test,
        test_predictions,
        _comparison_pairs(),
        n_resamples=n_resamples,
        seed=seed,
    )

    slices = slice_analysis(test, test_predictions)

    oracle, oracle_merged = oracle_diagnostics(test, diagnostics)
    mastery, mastery_frame = mastery_state_diagnostics(test, test, diagnostics)
    summary_path = data_path / "generation_summary.json"
    full_dataset_reference: Dict[str, Any] = {
        "source": str(summary_path),
        "note": (
            "Published generation_summary values are full-dataset simulator properties, "
            "not held-out test estimates."
        ),
    }
    if summary_path.is_file():
        with open(summary_path, "r", encoding="utf-8") as handle:
            generation_summary = json.load(handle)
        full_dataset_reference.update(
            {
                "oracle_latent_mastery_auroc": generation_summary.get(
                    "oracle_latent_mastery_auroc"
                ),
                "oracle_generating_probability_auroc": generation_summary.get(
                    "oracle_generating_probability_auroc"
                ),
                "sample_count": generation_summary.get("interaction_count"),
                "dataset_version": generation_summary.get("dataset_version"),
            }
        )
    oracle["full_dataset_reference"] = full_dataset_reference

    item_heldout = item_heldout_validation_analysis(
        interactions,
        train,
        validation,
        bkt_config=config,
        combined_c=combined_c,
        seed=seed,
    )

    audit = {
        "eligibility": eligibility_audit(interactions),
        "item_exposure": item_exposure_audit(interactions),
        "frozen_config": {
            "config_id": config.config_id,
            "version": config.version,
            "source_dataset": config.source_dataset,
            "status": config.status,
        },
    }

    result: Dict[str, Any] = {
        "metadata": {
            "dataset": str(data_path),
            "configs_dir": str(config_path),
            "seed": int(seed),
            "n_resamples": int(n_resamples),
            "random_seed_metadata": int(seed),
            "best_c": {
                "combined_item_bkt": combined_c,
                "combined_item_bkt_prior": combined_prior_c,
                "combined_item_concept_bkt": combined_concept_c,
                "item_logit_logistic": item_logit_c,
                "item_concept_logit_logistic": item_concept_logit_c,
            },
        },
        "audit": audit,
        "splits": {
            "train": {
                "rows": int(len(train)),
                "learners": int(train["student_id"].nunique()),
                "observed_positive_rate": float(train["correct"].mean()),
            },
            "validation": {
                "rows": int(len(validation)),
                "learners": int(validation["student_id"].nunique()),
                "observed_positive_rate": float(validation["correct"].mean()),
            },
            "test": {
                "rows": int(len(test)),
                "learners": int(test["student_id"].nunique()),
                "observed_positive_rate": float(test["correct"].mean()),
            },
        },
        "validation": validation_metrics,
        "test": test_metrics,
        "calibration": calibration_summary(test_metrics),
        "paired_bootstrap": bootstrap,
        "combined_hyperparameter_selection": {
            "combined_item_bkt": combined_c_table,
            "combined_item_bkt_prior": combined_prior_table,
            "combined_item_concept_bkt": combined_concept_table,
            "item_logit_logistic": item_logit_table,
            "item_concept_logit_logistic": item_concept_logit_table,
        },
        "combined_coefficients": {
            "combined_item_bkt": combined_model.coefficients(),
            "combined_item_bkt_prior": combined_prior_model.coefficients(),
            "combined_item_concept_bkt": combined_concept_model.coefficients(),
            "item_logit_logistic": item_logit_model.coefficients(),
            "item_concept_logit_logistic": item_concept_logit_model.coefficients(),
        },
        "oracle": oracle,
        "item_heldout_validation": item_heldout,
    }

    if write_outputs:
        output_path.mkdir(parents=True, exist_ok=True)
        with open(output_path / "controlled_model_comparison_metrics.json", "w", encoding="utf-8") as handle:
            json.dump(result, handle, indent=2, sort_keys=True)
        with open(output_path / "oracle_diagnostics.json", "w", encoding="utf-8") as handle:
            json.dump(oracle, handle, indent=2, sort_keys=True)
        with open(output_path / "mastery_state_diagnostics.json", "w", encoding="utf-8") as handle:
            json.dump(mastery, handle, indent=2, sort_keys=True)
        slices.to_csv(output_path / "controlled_model_comparison_slices.csv", index=False)
        mastery_columns = [
            column
            for column in (
                "interaction_id",
                "student_id",
                "sequence_index",
                "question_id",
                "primary_concept_id",
                "prior_interactions",
                "prior_attempts_concept",
                "difficulty",
                "hint_used",
                "is_multi_concept",
                "correct",
                "bkt_p_prior",
                "bkt_p_next",
                "latent_mastery_primary_before",
                "latent_mastery_primary_after",
                "history_depth_bin",
                "concept_attempt_bin",
                "concept_response_pattern",
            )
            if column in mastery_frame.columns
        ]
        mastery_frame[mastery_columns].to_csv(
            output_path / "mastery_state_diagnostic_rows.csv", index=False
        )

    return {
        "metrics": result,
        "mastery": mastery,
        "slices": slices,
        "oracle_merged": oracle_merged,
        "mastery_frame": mastery_frame,
    }
