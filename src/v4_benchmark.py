def add_response_history_features(targets: pd.DataFrame) -> pd.DataFrame:
    df = targets.sort_values(
        by=["student_id", "sequence_index", "timestamp_utc"],
        kind="mergesort",
    ).copy()

    student_grouped = df.groupby("student_id", sort=False)["correct"]
    concept_grouped = df.groupby(["student_id", "primary_concept_id"], sort=False)["correct"]
    for lag in (1, 2, 3):
        df[f"prior_correct_{lag}"] = student_grouped.shift(lag)
        df[f"prior_concept_correct_{lag}"] = concept_grouped.shift(lag)

    overall_columns = [f"prior_correct_{lag}" for lag in (1, 2, 3)]
    concept_columns = [f"prior_concept_correct_{lag}" for lag in (1, 2, 3)]
    df["prior_3_n"] = df[overall_columns].notna().sum(axis=1).astype(int)
    df["prior_3_correct"] = df[overall_columns].sum(axis=1, skipna=True).astype(int)
    df["prior_concept_3_n"] = df[concept_columns].notna().sum(axis=1).astype(int)
    df["prior_concept_3_correct"] = df[concept_columns].sum(axis=1, skipna=True).astype(int)
    return df


def _response_pattern(row: pd.Series, n_column: str, correct_column: str) -> str:
    n = int(row[n_column])
    correct = int(row[correct_column])
    if n == 0:
        return "no_prior"
    if correct == n:
        return "repeated_correct"
    if correct == 0:
        return "repeated_incorrect"
    return "mixed"


def _continuous_agreement(y_true: np.ndarray, y_pred: np.ndarray) -> Dict[str, Any]:
    true_series = pd.Series(y_true, dtype=float)
    pred_series = pd.Series(y_pred, dtype=float)
    difference = pred_series - true_series
    pearson = None
    spearman = None
    if len(true_series) >= 2 and true_series.nunique() >= 2 and pred_series.nunique() >= 2:
        pearson_value = pred_series.corr(true_series)
        spearman_value = pred_series.corr(true_series, method="spearman")
        pearson = float(pearson_value) if pd.notna(pearson_value) else None
        spearman = float(spearman_value) if pd.notna(spearman_value) else None
    return {
        "n": int(len(true_series)),
        "mae": float(np.mean(np.abs(difference))),
        "rmse": float(np.sqrt(np.mean(np.square(difference)))),
        "mean_bias": float(np.mean(difference)),
        "pearson": pearson,
        "spearman": spearman,
        "mean_predicted": float(pred_series.mean()),
        "mean_target": float(true_series.mean()),
    }


def _latent_calibration(y_true: np.ndarray, y_pred: np.ndarray, n_bins: int = 10) -> Dict[str, Any]:
    frame = pd.DataFrame({"target": y_true, "prediction": y_pred})
    frame["bin"] = pd.qcut(frame["prediction"], q=n_bins, duplicates="drop")
    grouped = frame.groupby("bin", observed=True).agg(
        count=("target", "size"),
        mean_predicted=("prediction", "mean"),
        mean_target=("target", "mean"),
    ).reset_index()
    total = len(frame)
    ece = float(
        np.sum(
            (grouped["count"] / total)
            * np.abs(grouped["mean_predicted"] - grouped["mean_target"])
        )
    )
    rows = [
        {
            "bin_low": float(row["bin"].left),
            "bin_high": float(row["bin"].right),
            "count": int(row["count"]),
            "mean_predicted": float(row["mean_predicted"]),
            "mean_target": float(row["mean_target"]),
        }
        for _, row in grouped.iterrows()
    ]
    return {"latent_ece": ece, "bins": rows}


def oracle_diagnostics(
    targets: pd.DataFrame,
    diagnostics: pd.DataFrame,
) -> Tuple[Dict[str, Any], pd.DataFrame]:
    required = ["interaction_id", "latent_mastery_primary_before", "generating_response_probability"]
    missing = [c for c in required if c not in diagnostics.columns]
    if missing:
        raise ValueError(f"Diagnostics DataFrame missing required columns: {missing}")

    merged = targets[["interaction_id", "student_id", "correct"]].merge(
        diagnostics,
        on="interaction_id",
        how="inner",
        validate="one_to_one",
    )
    if len(merged) != len(targets):
        raise ValueError(
            f"Diagnostics alignment failed: {len(merged)} diagnostics rows for {len(targets)} targets."
        )

    y = merged["correct"].to_numpy(dtype=int)
    signal_columns = {
        "latent_mastery_primary_before": "hidden primary-concept mastery before response",
        "effective_mastery_before": "hidden effective mastery before response",
        "p_learned_component": "hidden learned-response component",
        "generating_response_probability": "hidden full generating response probability",
    }

    results: Dict[str, Any] = {
        "sample_count": int(len(merged)),
        "student_count": int(merged["student_id"].nunique()),
        "observed_positive_rate": float(y.mean()),
        "signals": {},
    }
    for column, description in signal_columns.items():
        if column not in merged.columns:
            continue
        values = merged[column].to_numpy(dtype=float)
        metrics: Dict[str, Any] = {
            "description": description,
            "roc_auc": _constant_auc(y, values),
            "mean": float(np.mean(values)),
            "min": float(np.min(values)),
            "max": float(np.max(values)),
        }
        if column == "generating_response_probability":
            clipped = _clip_probabilities(values)
            metrics["log_loss"] = float(-np.mean(y * np.log(clipped) + (1 - y) * np.log(1 - clipped)))
            metrics["brier_score"] = float(np.mean((y - clipped) ** 2))
        results["signals"][column] = metrics

    return results, merged


def mastery_state_diagnostics(
    targets: pd.DataFrame,
    bkt_targets: pd.DataFrame,
    diagnostics: pd.DataFrame,
) -> Tuple[Dict[str, Any], pd.DataFrame]:
    required_bkt = ["interaction_id", "bkt_p_prior", "bkt_p_next"]
    missing_bkt = [c for c in required_bkt if c not in bkt_targets.columns]
    if missing_bkt:
        raise ValueError(f"BKT targets missing required columns: {missing_bkt}")

    history_targets = add_response_history_features(targets)
    existing_bkt_columns = [c for c in ("bkt_p_prior", "bkt_p_next") if c in history_targets.columns]
    if existing_bkt_columns:
        history_targets = history_targets.drop(columns=existing_bkt_columns)
    merged = history_targets.merge(
        bkt_targets[required_bkt],
        on="interaction_id",
        how="left",
        validate="one_to_one",
    ).merge(
        diagnostics,
        on="interaction_id",
        how="inner",
        validate="one_to_one",
    )
    if merged[required_bkt].isna().any().any():
        raise ValueError("BKT mastery diagnostics alignment failed.")

    merged["history_depth_bin"] = merged["prior_interactions"].map(_history_bin)
    merged["concept_attempt_bin"] = merged["prior_attempts_concept"].map(_concept_attempt_bin)
    merged["item_count_bin"] = merged["item_train_count"].map(_item_count_bin)
    merged["concept_response_pattern"] = merged.apply(
        lambda row: _response_pattern(row, "prior_concept_3_n", "prior_concept_3_correct"),
        axis=1,
    )
    merged["overall_response_pattern"] = merged.apply(
        lambda row: _response_pattern(row, "prior_3_n", "prior_3_correct"),
        axis=1,
    )

    before_target = merged["latent_mastery_primary_before"].to_numpy(dtype=float)
    after_target = merged["latent_mastery_primary_after"].to_numpy(dtype=float)
    bkt_prior = merged["bkt_p_prior"].to_numpy(dtype=float)
    bkt_next = merged["bkt_p_next"].to_numpy(dtype=float)

    results: Dict[str, Any] = {
        "sample_count": int(len(merged)),
        "student_count": int(merged["student_id"].nunique()),
        "before_response": _continuous_agreement(before_target, bkt_prior),
        "after_response": _continuous_agreement(after_target, bkt_next),
        "before_response_latent_calibration": _latent_calibration(before_target, bkt_prior),
        "after_response_latent_calibration": _latent_calibration(after_target, bkt_next),
        "slices": {},
    }

    slice_specs = {
        "history_depth": "history_depth_bin",
        "concept_attempts": "concept_attempt_bin",
        "item_train_count": "item_count_bin",
        "concept_response_pattern": "concept_response_pattern",
        "overall_response_pattern": "overall_response_pattern",
        "difficulty": "difficulty",
        "hint_used": "hint_used",
        "concept_composition": "is_multi_concept",
    }

    for slice_name, column in slice_specs.items():
        if column not in merged.columns:
            continue
        slice_rows: List[Dict[str, Any]] = []
        for value, group in merged.groupby(column, dropna=False):
            slice_rows.append(
                {
                    "value": str(value),
                    "n": int(len(group)),
                    "before_response": _continuous_agreement(
                        group["latent_mastery_primary_before"].to_numpy(dtype=float),
                        group["bkt_p_prior"].to_numpy(dtype=float),
                    ),
                    "after_response": _continuous_agreement(
                        group["latent_mastery_primary_after"].to_numpy(dtype=float),
                        group["bkt_p_next"].to_numpy(dtype=float),
                    ),
                }
            )
        results["slices"][slice_name] = slice_rows

    before_agreement = results["before_response"]
    results["interpretation_inputs"] = {
        "before_mae": before_agreement["mae"],
        "before_pearson": before_agreement["pearson"],
        "before_spearman": before_agreement["spearman"],
        "latent_ece": results["before_response_latent_calibration"]["latent_ece"],
    }
    return results, merged


def slice_analysis(
    targets: pd.DataFrame,
    predictions: Mapping[str, Sequence[float]],
    *,
    model_names: Sequence[str] = PRIMARY_MODELS,
) -> pd.DataFrame:
    frame = targets.copy()
    frame["history_depth_bin"] = frame["prior_interactions"].map(_history_bin)
    frame["concept_attempt_bin"] = frame["prior_attempts_concept"].map(_concept_attempt_bin)
    frame["item_count_bin"] = frame["item_train_count"].map(_item_count_bin)
    frame["concept_composition"] = np.where(frame["is_multi_concept"], "multi", "single")

    slice_specs = {
        "history_depth": "history_depth_bin",
        "concept_attempts": "concept_attempt_bin",
        "item_train_count": "item_count_bin",
        "concept_composition": "concept_composition",
        "hint_used": "hint_used",
        "is_assessment": "is_assessment",
        "difficulty": "difficulty",
        "subject": "subject",
    }

    rows: List[Dict[str, Any]] = []
    for slice_name, column in slice_specs.items():
        if column not in frame.columns:
            continue
        for value, group in frame.groupby(column, dropna=False):
            for model_name in model_names:
                if model_name not in predictions:
                    continue
                probabilities = _clip_probabilities(np.asarray(predictions[model_name])[group.index])
                metrics = evaluate_predictions(group["correct"], probabilities)
                rows.append(
                    {
                        "slice_name": slice_name,
                        "slice_value": str(value),
                        "model": model_name,
                        "n": int(len(group)),
                        "student_count": int(group["student_id"].nunique()),
                        "observed_positive_rate": metrics["observed_positive_rate"],
                        "log_loss": metrics["log_loss"],
                        "brier_score": metrics["brier_score"],
                        "roc_auc": metrics["roc_auc"],
                        "expected_calibration_error": metrics["expected_calibration_error"],
                    }
                )
    return pd.DataFrame(rows)


def _item_heldout_ids(interactions: pd.DataFrame, *, fraction: float, seed: int) -> List[str]:
    items = np.array(sorted(interactions["question_id"].astype(str).unique()))
    n_holdout = int(round(len(items) * fraction))
    if n_holdout <= 0 or n_holdout >= len(items):
        raise ValueError(f"Invalid item holdout fraction {fraction} for {len(items)} items.")
    rng = np.random.default_rng(seed)
    selected = rng.choice(items, size=n_holdout, replace=False)
    return sorted(str(item) for item in selected)


def item_heldout_validation_analysis(
    interactions: pd.DataFrame,
    train_targets: pd.DataFrame,
    validation_targets: pd.DataFrame,
    *,
    bkt_config: BKTConfig,
    combined_c: float,
    fraction: float = 0.20,
    seed: int = DEFAULT_SEED,
) -> Dict[str, Any]:
    """Auxiliary unseen-item analysis on validation learners.

    A deterministic subset of item IDs is removed from the item-effect fitting
    data. Models are then evaluated only on validation interactions using those
    held-out items. No test interaction is read or modified.
    """

    heldout_items = set(_item_heldout_ids(interactions, fraction=fraction, seed=seed))
    train_seen = train_targets.loc[~train_targets["question_id"].astype(str).isin(heldout_items)].copy()
    validation_heldout = validation_targets.loc[
        validation_targets["question_id"].astype(str).isin(heldout_items)
    ].copy()
    validation_seen = validation_targets.loc[
        ~validation_targets["question_id"].astype(str).isin(heldout_items)
    ].copy()

    if train_seen.empty or validation_heldout.empty:
        raise ValueError("Item-held-out analysis produced an empty fitting or evaluation split.")

    baselines = fit_static_baselines(train_seen)
    combined = CombinedItemBKTModel(
        bkt_feature="p_pred",
        include_concept=False,
        C=combined_c,
    ).fit(train_seen)

    predictions_heldout = static_baseline_predictions(baselines, validation_heldout)
    predictions_heldout["bkt_concept_fitted"] = _clip_probabilities(
        validation_heldout["bkt_p_pred"]
    )
    predictions_heldout["combined_item_bkt"] = combined.predict_proba(validation_heldout)

    predictions_seen = static_baseline_predictions(baselines, validation_seen)
    predictions_seen["bkt_concept_fitted"] = _clip_probabilities(
        validation_seen["bkt_p_pred"]
    )
    predictions_seen["combined_item_bkt"] = combined.predict_proba(validation_seen)

    return {
        "fraction": float(fraction),
        "seed": int(seed),
        "heldout_item_count": int(len(heldout_items)),
        "heldout_items": sorted(heldout_items),
        "train_seen_rows": int(len(train_seen)),
        "validation_heldout_rows": int(len(validation_heldout)),
        "validation_seen_rows": int(len(validation_seen)),
        "validation_heldout_models": evaluate_model_predictions(
            validation_heldout, predictions_heldout
        ),
        "validation_seen_models": evaluate_model_predictions(
            validation_seen, predictions_seen
        ),
        "combined_c": float(combined_c),
        "bkt_config_id": bkt_config.config_id,
        "note": (
            "Auxiliary analysis uses validation learners and item-disjoint fitting only. "
            "The frozen test partition is untouched."
        ),
    }


